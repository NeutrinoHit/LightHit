#!/usr/bin/env python
"""Check the idea registry, fold measured results into it and write REPORT.md.

    python experiments/report.py            # check, update [result] blocks, write REPORT.md
    python experiments/report.py --check    # only validate the registry

Reads experiments/ideas/*.toml and experiments/results/<idea>/<case>.json
(+ .npz responses). For every case of an idea, accuracy is recomputed from the
saved responses against the case's reference, and speed is the ratio of its
wall time to the baseline case's (same input, same thread count). The
``[result]`` block at the end of each idea file is regenerated from these
records (date, machine, commit, input hashes, metrics); everything above the
marker line is written by hand and never touched.
"""
from __future__ import annotations

import argparse
import re
import json
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))

IDEAS = HERE / "ideas"
REPORT = HERE / "REPORT.md"
MARKER = "# ---- measured (generated by experiments/report.py from experiments/results; do not edit below) ----"
KINDS = {"table-builder", "validation", "probe", "reference", "alternative-option", "route", "tool"}
STATUS_PREFIXES = ("default", "used-by-default", "tool", "superseded-by:", "rejected", "open",
                   "not-reproducible")
REQUIRED = ("id", "title", "question", "kind", "status", "code", "how-to-run", "inputs", "notes")


def load_ideas():
    ideas = {}
    for path in sorted(IDEAS.glob("*.toml")):
        text = path.read_text()
        head = text.split(MARKER)[0]
        try:
            data = tomllib.loads(text)
        except tomllib.TOMLDecodeError as exc:
            raise SystemExit(f"{path.name}: {exc}")
        data["_path"], data["_head"] = path, head
        ideas[data.get("id", path.stem)] = data
    return ideas


def check(ideas) -> list[str]:
    errors = []
    scripts_seen = set()
    for key, idea in ideas.items():
        name = idea["_path"].name
        for field in REQUIRED:
            if field not in idea:
                errors.append(f"{name}: missing {field}")
        if idea.get("id") != idea["_path"].stem:
            errors.append(f"{name}: id {idea.get('id')!r} differs from the file name")
        if idea.get("kind") not in KINDS:
            errors.append(f"{name}: kind {idea.get('kind')!r} not in {sorted(KINDS)}")
        status = str(idea.get("status", ""))
        if not status.startswith(STATUS_PREFIXES):
            errors.append(f"{name}: status {status!r}")
        if status.startswith("superseded-by:") and status.split(":", 1)[1] not in ideas:
            errors.append(f"{name}: superseded by unknown idea {status.split(':', 1)[1]}")
        if status.startswith("not-reproducible") and not idea.get("not_reproducible_reason"):
            errors.append(f"{name}: not-reproducible needs not_reproducible_reason")
        code = idea.get("code", {})
        for script in code.get("scripts", []):
            scripts_seen.add(script)
            if not (ROOT / script).exists():
                errors.append(f"{name}: script {script} does not exist")
        for module in code.get("modules", []):
            rel = Path("src", *module.split(".")).with_suffix(".py")
            pkg = Path("src", *module.split("."), "__init__.py")
            if not (ROOT / rel).exists() and not (ROOT / pkg).exists():
                errors.append(f"{name}: module {module} not found")
    infrastructure = {"scripts/shower_basis/paths.py"}
    for script in sorted(_all_scripts() - scripts_seen - infrastructure):
        errors.append(f"script {script} is not referenced by any idea")
    return errors


def _all_scripts():
    found = set()
    for path in (ROOT / "scripts").rglob("*"):
        if path.suffix in (".py", ".sh") and "__pycache__" not in path.parts:
            found.add(str(path.relative_to(ROOT)))
    for path in (ROOT / "tools").rglob("*.py") if (ROOT / "tools").exists() else ():
        found.add(str(path.relative_to(ROOT)))
    return found


# ------------------------------------------------------------------ results
def _results():
    from harness.record import RESULTS
    out = {}
    for path in sorted(RESULTS.glob("*/*.json")):
        try:
            record = json.loads(path.read_text())
        except json.JSONDecodeError:
            continue
        if "idea" in record and "case" in record:
            out[f"{record['idea']}/{record['case']}"] = record
    return out


KEYWORDS = ("error", "l1", "speedup", "passed", "missed", "lost", "gained", "accepted", "identical",
            "max_", "bias", "relative", "zscore", "pull", "seconds")


def auto_headline(report, limit=8):
    """Up to ``limit`` numeric or boolean leaves of a script report whose key names
    an error, an L1, a speed-up or a pass flag, taken as they are (first found)."""
    found = {}

    def walk(value, path):
        if len(found) >= limit:
            return
        if isinstance(value, dict):
            for key, item in value.items():
                walk(item, f"{path}.{key}" if path else str(key))
        elif isinstance(value, list) and value and len(value) <= 12 and not isinstance(value[0], (dict, list)):
            if all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in value) and any(
                    k in path.lower() for k in KEYWORDS):
                found[path + " (max)"] = max(value, key=abs)
        elif isinstance(value, list):
            for i, item in enumerate(value[:3]):
                walk(item, f"{path}[{i}]")
        elif isinstance(value, (bool, int, float)) and any(k in path.lower() for k in KEYWORDS):
            found[path] = value
    walk(report, "")
    return found


_PAIR = re.compile(r"([A-Za-z][\w.]*)=([^\s,=]+)")


def text_headline(stdout, limit=12):
    """Headline of a script that prints text instead of a JSON report.

    * ``written: <file>.json`` (the run-*-example scripts): that file is the report;
    * ``checks failed: none`` / ``checks failed: <list>``: a pass flag;
    * lines of ``key=value`` pairs (the exp*.py studies): one row per line, the
      non-metric pairs naming the row and the metric pairs as values;
    * otherwise the last three lines of the output, verbatim.
    """
    found = {}
    for line in stdout.splitlines():
        if line.startswith("written: ") and line.strip().endswith(".json"):
            path = Path(line[len("written: "):].strip())
            if path.is_file():
                try:
                    found.update(auto_headline(json.loads(path.read_text())))
                except ValueError:
                    pass
        elif line.startswith("checks failed: "):
            found["checks_failed"] = line[len("checks failed: "):].strip()
    rows = []
    for line in stdout.splitlines():
        pairs = _PAIR.findall(line)
        if len(pairs) < 3:
            continue
        label = " ".join(f"{k}={v}" for k, v in pairs if not any(
            w in k.lower() for w in KEYWORDS + ("rel", "abs", "total", "apply", "compile", "readout", "prepare", "cells")))
        values = {k: v for k, v in pairs if any(w in k.lower() for w in KEYWORDS + ("rel", "abs"))}
        if values:
            rows.append((label or f"line {len(rows) + 1}", values))
    for label, values in rows[-limit:]:
        found[label] = ", ".join(f"{k}={v}" for k, v in values.items())
    if not found:
        lines = [x.strip() for x in stdout.splitlines() if x.strip()]
        if lines:
            found["output_tail"] = _portable(" | ".join(lines[-3:]))[:400]
    return found


def _portable(text):
    """Text without this machine's absolute paths."""
    import os
    from harness.record import ROOT
    text = text.replace(str(ROOT) + "/", "")
    data = os.environ.get("LIGHTHIT_DATA")
    if data:
        text = text.replace(data.rstrip("/"), "$LIGHTHIT_DATA")
    return re.sub(r"(?:/Users|/home|/private|/tmp)/[^\s'\"]+", "<local path>", text)


def _accuracy(record, results, case=None):
    """Metrics vs the reference, recomputed from saved responses when possible."""
    from harness import metrics
    from harness.record import RESULTS, load_response
    ref = record.get("reference") or (case.reference if case is not None else None)
    if not ref or record.get("kind") != "response" or record.get("status") != "ok":
        return record.get("accuracy")
    mine = RESULTS / f"{record['idea']}/{record['case']}.npz"
    theirs = RESULTS / f"{ref}.npz"
    if mine.is_file() and theirs.is_file():
        a, b = load_response(mine), load_response(theirs)
        orders = tuple(k for k in (0, 1, 2) if _computed(a, k) and _computed(b, k))
        out = metrics.compare(a, b, orders=orders)
        if 2 not in orders:
            # the active sets follow from all orders: without order >=2 they are not comparable
            out.pop("active", None)
            out["orders_compared"] = [metrics.ORDERS[k] for k in orders]
        return out
    return record.get("accuracy")


def _computed(response, k):
    computed = [str(x) for x in response.get("orders_computed", ["0", "1", "2"])]
    return str(k) in computed or (k == 2 and ">=2" in computed)


def _baseline_key(idea, key, results, cases):
    case = cases.get(key)
    if case is not None and case.baseline:
        return case.baseline
    explicit = idea.get("baseline")
    name = key.split("/", 1)[1]
    base, _, threads = name.partition("@")
    if explicit:
        return f"{explicit}/{base}" + (f"@{threads}" if threads else "")
    return None


def gather(ideas):
    from harness.cases import load_all
    cases = load_all()
    results = _results()
    rows = {}
    for key, idea in ideas.items():
        entries = []
        listed = idea.get("cases", [])
        keys = sorted({k for k in results if k.split("/")[0] == key}
                      | {c for c in listed})
        for case_key in keys:
            record = results.get(case_key)
            if record is None:
                entries.append(dict(case=case_key, status="not run"))
                continue
            entry = dict(case=case_key, status=record.get("status"), date=record.get("date"),
                         commit=(record.get("source") or {}).get("commit"),
                         src_modified=(record.get("source") or {}).get("src_modified"),
                         machine=_machine(record.get("machine") or {}),
                         threads=record.get("threads"), inputs=record.get("inputs"),
                         timing=record.get("timing"), summary=record.get("summary"),
                         error=_error_text(record.get("error")),
                         reference=record.get("reference") or getattr(cases.get(case_key.split("@")[0]), "reference", None))
            accuracy = _accuracy(record, results, cases.get(case_key.split("@")[0]))
            if accuracy:
                entry["accuracy"] = accuracy
            if record.get("metrics") is not None:
                entry["metrics"] = record["metrics"]
                m = entry["metrics"]
                if isinstance(m, dict) and not m.get("headline") and m.get("report") is not None:
                    m["headline"] = auto_headline(m["report"])
                if isinstance(m, dict) and not m.get("headline") and m.get("stdout_tail"):
                    m["headline"] = text_headline(_full_stdout(record) or m["stdout_tail"])
            base = _baseline_key(idea, case_key, results, cases)
            if base and base in results and results[base].get("timing") and record.get("timing"):
                entry["speed_vs_baseline"] = dict(
                    baseline=base,
                    wall_ratio=record["timing"]["wall_s"] / results[base]["timing"]["wall_s"])
            entries.append(entry)
        rows[key] = entries
    return rows


def _error_text(error):
    """The exception line of an error (a script's traceback ends with it), without local paths."""
    if not error:
        return None
    head, _, tail = str(error).partition(": script exited with ")
    lines = [x.strip() for x in tail.splitlines() if x.strip()] if tail else []
    if lines:
        text = f"{head}: script exited with {lines[0].split(':')[0]}: {lines[-1]}"
    else:
        text = str(error).strip().splitlines()[-1]
    return _portable(text)


def _full_stdout(record):
    """The script's whole stdout from its log (the record keeps only its tail)."""
    from harness.record import RESULTS
    log = (record.get("metrics") or {}).get("log")
    if not log or not (RESULTS / log).is_file():
        return None
    text = (RESULTS / log).read_text()
    head, _, rest = text.partition("\n\n")
    return rest.split("\n--- stderr ---\n")[0]


def _machine(m):
    return dict(cpu=m.get("cpu"), cpu_count=m.get("cpu_count"), python=m.get("python"),
                numba=m.get("numba"), numpy=m.get("numpy"), load_average=m.get("load_average"),
                numba_threads=m.get("numba_threads"))


# --------------------------------------------------------------- TOML out
def _toml_value(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if value != value:
            return "nan"
        return repr(float(f"{value:.6g}"))
    if value is None:
        return '"none"'
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_toml_value(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{_key(k)} = {_toml_value(v)}" for k, v in value.items()
                                if v is not None) + " }"
    return json.dumps(str(value), ensure_ascii=False)


def _key(k):
    k = str(k)
    return k if k.replace("_", "").replace("-", "").isalnum() else json.dumps(k)


def _compact(entry):
    out = {k: entry[k] for k in ("status", "date", "commit", "threads") if entry.get(k) is not None}
    if entry.get("src_modified"):
        out["src_modified"] = True
    if entry.get("machine"):
        out["machine"] = {k: v for k, v in entry["machine"].items() if v is not None}
    if entry.get("inputs"):
        out["inputs_sha256"] = {k: v[:16] for k, v in entry["inputs"].items()}
    if entry.get("timing"):
        out["timing"] = {k: round(v, 3) if isinstance(v, (int, float)) else v
                         for k, v in entry["timing"].items()}
    if entry.get("summary"):
        s = entry["summary"]
        out["summary"] = dict(active=s.get("active"),
                              charge_pe_by_order=[round(x, 5) for x in s.get("charge_pe_by_order", [])])
    if entry.get("reference"):
        out["reference"] = entry["reference"]
    acc = entry.get("accuracy")
    if acc:
        for order, m in acc.get("orders", {}).items():
            out[f"order_{order.replace('>=', 'ge')}"] = {
                k: (round(v, 6) if isinstance(v, float) else v) for k, v in
                dict(charge_bias=m.get("charge_bias"), bin_l1=m.get("bin_l1"),
                     worst_om=(m.get("worst_om") or {}).get("relative_error")).items()
                if v is not None}
        out["active_agreement"] = acc.get("active")
    if entry.get("speed_vs_baseline"):
        out["wall_vs_baseline"] = round(entry["speed_vs_baseline"]["wall_ratio"], 4)
    metrics = entry.get("metrics")
    if isinstance(metrics, dict) and isinstance(metrics.get("headline"), dict):
        out["metrics"] = _flat(metrics["headline"])
    elif isinstance(metrics, dict) and metrics.get("log"):
        out["log"] = metrics["log"]
    if entry.get("error"):
        out["error"] = entry["error"][:300]
    return out


def _flat(value, depth=0):
    """Metrics dicts as TOML-safe nested tables (lists of dicts become JSON strings)."""
    if isinstance(value, dict):
        return {str(k): _flat(v, depth + 1) for k, v in value.items() if v is not None}
    if isinstance(value, (list, tuple)):
        if all(isinstance(v, (int, float, str, bool)) for v in value) and len(value) <= 32:
            return list(value)
        return json.dumps(value, default=str)[:2000]
    return value


def write_results(ideas, rows):
    for key, idea in ideas.items():
        lines = [MARKER]
        for entry in rows.get(key, []):
            if entry.get("status") == "not run":
                continue
            owner, case = entry["case"].split("/", 1)
            lines.append(f"\n[result.{_key(case if owner == key else entry['case'])}]")
            for k, v in _compact(entry).items():
                if isinstance(v, dict) and k in ("metrics",):
                    continue
                lines.append(f"{_key(k)} = {_toml_value(v)}")
            if "metrics" in _compact(entry):
                lines.append(f"metrics = {_toml_value(_compact(entry)['metrics'])}")
        head = idea["_head"].rstrip() + "\n"
        text = head + ("\n" + "\n".join(lines) + "\n" if len(lines) > 1 else "")
        tomllib.loads(text)        # never write an unreadable file
        idea["_path"].write_text(text)


# ------------------------------------------------------------- REPORT.md
def _pct(x):
    return "" if x is None else f"{100 * x:.3g}%"


def _accuracy_text(entry):
    acc = entry.get("accuracy")
    if not acc:
        return ""
    parts = []
    for order, m in acc["orders"].items():
        if m.get("reference_charge_pe") in (None, 0):
            continue
        bits = [f"bias {_pct(m.get('charge_bias'))}"]
        if m.get("bin_l1") is not None:
            bits.append(f"L1 {_pct(m['bin_l1'])}")
        if m.get("worst_om"):
            bits.append(f"worst {_pct(m['worst_om']['relative_error'])}")
        parts.append(f"{order}: " + ", ".join(bits))
    if acc.get("orders_compared"):
        parts.append("orders " + "+".join(acc["orders_compared"]) + " only")
    a = acc.get("active", {})
    if a.get("only_response") or a.get("only_reference"):
        parts.append(f"active +{a.get('only_response')}/-{a.get('only_reference')}")
    return "; ".join(parts)


def _metrics_text(entry):
    m = entry.get("metrics")
    if not isinstance(m, dict):
        return ""
    head = m.get("headline")
    if isinstance(head, dict):
        return "; ".join(f"{k} {v:.4g}" if isinstance(v, float) else f"{k} {v}" for k, v in head.items())
    return ""


def write_report(ideas, rows):
    lines = ["# Idea registry: measured report", "",
             "Generated by `experiments/report.py` from `experiments/ideas/*.toml` and the raw",
             "results in `experiments/results/` (not in git). Do not edit by hand.", "",
             "Accuracy is relative to the case's reference (named in the case column of the",
             "detail table; see `experiments/README.md` for the references). Order labels: 0, 1,",
             "\">=2\", total. bias = (sum Q - sum Q_ref)/sum Q_ref; L1 = summed |bin difference| /",
             "summed |reference bins| over OMs active in both; worst = largest relative charge error",
             "of an OM with reference charge >= 0.01 pe. Speed is wall time divided by the",
             "baseline case's wall time on the same input and thread count (< 1 is faster).", "",
             "## Summary", "", "| Idea | Kind | Status | Measured | Verdict |", "|---|---|---|---|---|"]
    for key in sorted(ideas, key=lambda k: (ideas[k].get("area", ""), k)):
        idea = ideas[key]
        entries = rows.get(key, [])
        ok = sum(e.get("status") == "ok" for e in entries)
        failed = sum(e.get("status") == "error" for e in entries)
        measured = f"{ok} ok" + (f", {failed} failed" if failed else "") if entries else "no case"
        verdict = str(idea.get("verdict", "")).replace("\n", " ")
        lines.append(f"| [{key}](ideas/{key}.toml) | {idea.get('kind')} | {idea.get('status')} | "
                     f"{measured} | {verdict} |")
    lines += ["", "## Measured cases", "",
              "| Idea / case | Threads | Wall s | CPU s | RSS MiB | vs baseline | Accuracy vs reference |",
              "|---|---:|---:|---:|---:|---:|---|"]
    for key in sorted(rows):
        for entry in rows[key]:
            if entry.get("status") == "not run":
                continue
            t = entry.get("timing") or {}
            speed = entry.get("speed_vs_baseline")
            text = (_accuracy_text(entry) or _metrics_text(entry)
                    or (f"error: {entry['error'][:120]}" if entry.get("error") else ""))
            lines.append(f"| {entry['case']} | {entry.get('threads') or ''} | "
                         f"{t.get('wall_s', float('nan')):.2f} | {t.get('cpu_s', float('nan')):.2f} | "
                         f"{t.get('peak_rss_mib', float('nan')):.0f} | "
                         f"{'' if not speed else f'{speed['wall_ratio']:.3g}'} | {text} |")
    machines = {json.dumps(e.get("machine"), sort_keys=True) for es in rows.values() for e in es
                if e.get("machine")}
    commits = sorted({str(e.get("commit")) for es in rows.values() for e in es if e.get("commit")})
    lines += ["", "## Provenance", "", f"Commits of the measured source: {', '.join(commits) or 'none'}.",
              "Machines:", ""]
    described = sorted({f"* {m.get('cpu')} ({m.get('cpu_count')} cores), Python {m.get('python')}, "
                        f"numpy {m.get('numpy')}, numba {m.get('numba')}"
                        for m in map(json.loads, machines)})
    lines += described
    loads = sorted(float((json.loads(m).get("load_average") or [0])[0]) for m in machines)
    if loads:
        lines += ["", f"One-minute load average at the start of a case: median {loads[len(loads) // 2]:.1f}, "
                      f"range {loads[0]:.1f}-{loads[-1]:.1f} (each [result] block records its own)."]
    nr = [(k, str(v.get("not_reproducible_reason"))) for k, v in ideas.items()
          if str(v.get("status")).startswith("not-reproducible")]
    nr += [(k, f"(part) {part}") for k, v in ideas.items() for part in v.get("not_reproducible_parts", [])]
    if nr:
        lines += ["", "## Not reproducible", "", "| Idea | Reason |", "|---|---|"]
        for k, reason in sorted(nr):
            lines.append(f"| {k} | {reason.replace(chr(10), ' ').strip()} |")
    REPORT.write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    ideas = load_ideas()
    errors = check(ideas)
    for e in errors:
        print("registry:", e)
    if args.check:
        raise SystemExit(1 if errors else 0)
    rows = gather(ideas)
    write_results(ideas, rows)
    write_report(load_ideas(), rows)
    print(f"{len(ideas)} ideas, {sum(len(r) for r in rows.values())} cases; wrote {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
