#!/usr/bin/env python3
"""Compare the shower-basis route with the hybrid on one NTSim event.

Sources can be generated by NTSim or loaded from a stored G4 HDF5 event,
then placed in the same NTSim BGVD water and detector. Each method should
run in a separate process for comparable peak RSS. Data and outputs stay
outside Git; this script does not build the ordinary RTE cache.
"""
import argparse
import json
import resource
import sys
from itertools import islice
from pathlib import Path
from time import perf_counter

import numpy as np


def compare(reference_path, candidate_path, output):
    with np.load(reference_path, allow_pickle=False) as a, np.load(
            candidate_path, allow_pickle=False) as b:
        active = a["active"] | b["active"]
        bright = np.flatnonzero(active)
        bright = bright[np.argsort(-a["charge"][bright].sum(axis=1))[:10]]
        result = {
            "reference": str(reference_path), "candidate": str(candidate_path),
            "active_reference": int(a["active"].sum()),
            "active_candidate": int(b["active"].sum()),
            "active_lost": int((a["active"] & ~b["active"]).sum()),
            "active_gained": int((b["active"] & ~a["active"]).sum()),
            "prompt_charge_bitwise": bool(np.array_equal(a["charge"][:, :2],
                                                          b["charge"][:, :2])),
            "prompt_bins_bitwise": bool(np.array_equal(a["bins"][:, :, :2],
                                                        b["bins"][:, :, :2])),
        }
        for name, columns in (("ge2", [2]), ("total", [0, 1, 2])):
            qa, qb = a["charge"][:, columns].sum(1), b["charge"][:, columns].sum(1)
            ba, bb = a["bins"][:, :, columns].sum(2), b["bins"][:, :, columns].sum(2)
            dq = np.abs(qb - qa)
            db = np.abs(bb - ba)
            result[name] = {
                "charge_max_abs_pe": float(dq.max()),
                "charge_max_rel_bright": float((dq[bright] /
                    np.maximum(np.abs(qa[bright]), 1e-300)).max()),
                "bins_l1_max_bright": float((db[bright].sum(1) /
                    np.maximum(np.abs(ba[bright]).sum(1), 1e-300)).max()),
                "bins_l1_global": float(db.sum() /
                    max(np.abs(ba).sum(), 1e-300)),
            }
        edges = np.arange(-60., 745., 5.)
        early = (edges[:-1] >= 0) & (edges[1:] <= 20)
        result["early_0_20ns_max_abs_pe"] = float(np.abs(
            a["bins"][:, early].sum((1, 2))
            - b["bins"][:, early].sum((1, 2))).max())
    if output is not None:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(json.dumps(result, indent=2))
    print(json.dumps(result, indent=2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--method", choices=("hybrid", "basis", "cells", "compare"),
                        required=True)
    parser.add_argument("--source", choices=("ntsim", "g4"), default="ntsim")
    parser.add_argument("--g4-file", type=Path)
    parser.add_argument("--event", type=int, default=5)
    parser.add_argument("--pdg", type=int, default=11)
    parser.add_argument("--energy", type=float, default=100.)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--position", type=float, nargs=3, default=(5., -269.5, 330.))
    parser.add_argument("--direction", type=float, nargs=3, default=(.35, -.20, .915))
    parser.add_argument("--cone-model", choices=("frozen", "spectral"), default="frozen")
    parser.add_argument("--cache", type=Path)
    parser.add_argument("--pack", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--repeat", type=int, default=1)
    parser.add_argument("--reference", type=Path)
    parser.add_argument("--candidate", type=Path)
    args = parser.parse_args()
    if args.method == "compare":
        if args.reference is None or args.candidate is None:
            parser.error("compare requires --reference and --candidate")
        compare(args.reference, args.candidate, args.output)
        return
    if args.cache is None or args.pack is None:
        parser.error("transport requires --cache and --pack")
    if args.source == "g4" and args.g4_file is None:
        parser.error("--source g4 requires --g4-file")

    import ntsim
    import lighthit as lh
    from ntsim.LightTransport import bgvd_model_from_ntsim, source_from_event
    from ntsim.event_chain import Chain, EmptyEventSource
    from lighthit.shower_basis import transport_hybrid_basis

    model = bgvd_model_from_ntsim(ntsim.bgvd.Telescope(n_clusters=(1,)),
                                  ntsim.bgvd.Water())
    cfg = lh.KernelConfig(
        omega_per_ns=np.linspace(0., 1.2, 65),
        readout_omega_per_ns=np.linspace(0., 1.2, 321),
        relative_time_edges_ns=np.arange(-60., 745., 5.),
        cache_directory=args.cache, cache_policy="require")
    kernel = model.kernel(cfg)
    if args.method in ("basis", "cells") and (args.pack / "pack.json").is_file():
        load_start = perf_counter()
        kernel.ge2_kernel_store(args.pack)
        print("mmap_pack_seconds", perf_counter() - load_start, flush=True)
    direction = np.asarray(args.direction, float)
    direction /= np.linalg.norm(direction)
    if args.source == "g4":
        source = lh.G4Shower.from_hdf5(args.g4_file, event=args.event).placed(
            lh.SourcePose(args.position, direction, 0.))
    else:
        chain = Chain(
            ntsim.primary.ToyGen(energy=args.energy, pdg=args.pdg,
                                 position=tuple(args.position),
                                 direction=tuple(direction), time=0.) << "primary_gen",
            ntsim.modules.ParticlePropagator(
                random_seed=args.seed, enable_cherenkov=False,
                cascade_bounds_e=(0., 0.)) << "g4prop")
        event = next(islice(chain(EmptyEventSource()), 1))
        phase_max = (float(np.max(model.medium.phase_index))
                     if args.cone_model == "spectral" else None)
        source = source_from_event(event, cone_model=args.cone_model,
                                   max_phase_index=phase_max)
    print("LightHit", lh.__version__, "source_elements", len(source.elements), flush=True)
    args.output.mkdir(parents=True, exist_ok=True)
    for trial in range(args.repeat):
        start = perf_counter()
        if args.method == "hybrid":
            response = kernel.transport_hybrid(source, frequency_nodes=65)
        elif args.method == "basis":
            response = kernel.transport_hybrid(source, frequency_nodes=65,
                                               ge2_basis=lh.ShowerBasis())
        else:
            response = transport_hybrid_basis(kernel, source, lh.ShowerBasis(),
                                              frequency_nodes=65, representation="cells")
        wall = perf_counter() - start
        prefix = args.output / f"{args.method}-{trial}"
        np.savez_compressed(prefix.with_suffix(".npz"),
                            charge=response.charge_components_pe,
                            bins=response.components_pe, active=response.active,
                            origin=response.time_origin_ns,
                            spectrum_ge2=response.spectrum_ge2_pe,
                            omega=response.omega_per_ns)
        peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
        peak_mib = peak / (2**20 if sys.platform == "darwin" else 2**10)
        report = {"method": args.method, "trial": trial, "wall_seconds": wall,
                  "peak_rss_mib": peak_mib, "active": int(response.active.sum()),
                  "source_elements": len(source.elements),
                  "metadata": response.metadata}
        prefix.with_suffix(".json").write_text(json.dumps(report, default=str))
        print(args.method, trial, "seconds", wall, "peak_mib", peak_mib,
              "active", report["active"], flush=True)
        if args.method == "basis" and not (args.pack / "pack.json").is_file():
            save_start = perf_counter()
            kernel.ge2_kernel_store().save(args.pack)
            print("pack_save_seconds", perf_counter() - save_start, flush=True)


if __name__ == "__main__":
    main()
